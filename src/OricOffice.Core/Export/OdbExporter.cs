using System.Globalization;
using System.IO.Compression;
using System.Text;
using OricOffice.Core.Model;

namespace OricOffice.Core.Export;

/// <summary>
/// Writes LibreOffice Base .odb packages: an ODF database front-end whose
/// connection resource is <c>sdbc:embedded:hsqldb</c>, plus an embedded HSQLDB
/// 1.8 database stored entirely as text (<c>database/properties</c> clean-state
/// marker and <c>database/script</c> SQL replay). Tables are MEMORY tables —
/// LibreOffice's default for embedded databases — which HSQLDB persists in the
/// script file alone, so no binary engine files (.data/.backup) are needed.
/// </summary>
public static class OdbExporter
{
    private const string BaseMime = "application/vnd.oasis.opendocument.base";

    public static void Export(OricFile file, string path)
    {
        var script = BuildScript(file.Table);
        var content = BuildContentXml(file.Table);
        var manifest = BuildManifest();

        var fullPath = Path.GetFullPath(path);
        var dir = Path.GetDirectoryName(fullPath);
        if (!string.IsNullOrEmpty(dir)) Directory.CreateDirectory(dir);
        if (File.Exists(fullPath)) File.Delete(fullPath);

        using var stream = new FileStream(fullPath, FileMode.CreateNew);
        using var zip = new ZipArchive(stream, ZipArchiveMode.Create);

        // ODF rule: mimetype first and stored uncompressed.
        var mimeEntry = zip.CreateEntry("mimetype", CompressionLevel.NoCompression);
        using (var s = mimeEntry.Open())
        {
            var bytes = Encoding.ASCII.GetBytes(BaseMime);
            s.Write(bytes, 0, bytes.Length);
        }

        AddEntry(zip, "META-INF/manifest.xml", manifest);
        AddEntry(zip, "content.xml", content);
        AddEntry(zip, "settings.xml", SettingsXml());
        // Clean shutdown state (HSQLDB 1.8 recovery: modified=no).
        AddEntry(zip, "database/properties", "modified=no\n");
        AddEntry(zip, "database/script", script);
    }

    // ---------------------------------------------------------------- HSQLDB script

    /// <summary>Builds the HSQLDB 1.8 replay script: one statement per line, no semicolons.</summary>
    internal static string BuildScript(TableDocument table)
    {
        var sb = new StringBuilder();
        sb.Append("CREATE USER SA PASSWORD \"\" ADMIN\n");
        sb.Append("CREATE SCHEMA PUBLIC AUTHORIZATION DBA\n");
        sb.Append("SET SCHEMA PUBLIC\n");

        var name = string.IsNullOrWhiteSpace(table.Name) ? "Table1" : table.Name;
        var fields = table.Fields;

        long maxId = 0;
        foreach (var record in table.Records)
        {
            if (record.Id > maxId) maxId = record.Id;
        }

        // Column types are only as strict as the data allows: a typed column
        // that would reject any stored value falls back to VARCHAR.
        var columnDdl = new List<string>
        {
            $"ID INTEGER GENERATED BY DEFAULT AS IDENTITY(START WITH {maxId + 1})",
        };
        foreach (var field in fields)
            columnDdl.Add($"{Quote(field.Name)} {ColumnSqlType(field, table.Records)}");

        sb.Append("CREATE MEMORY TABLE PUBLIC.")
          .Append(Quote(name))
          .Append('(').Append(string.Join(", ", columnDdl)).Append(")\n");

        foreach (var record in table.Records)
        {
            var values = new List<string> { record.Id.ToString(CultureInfo.InvariantCulture) };
            foreach (var field in fields)
                values.Add(SqlLiteral(field, record.Get(field.Name)));
            sb.Append("INSERT INTO PUBLIC.")
              .Append(Quote(name))
              .Append(" VALUES(").Append(string.Join(", ", values)).Append(")\n");
        }

        return sb.ToString();
    }

    private static string ColumnSqlType(FieldDef field, IReadOnlyList<RecordRow> records)
    {
        var values = records
            .Select(r => r.Get(field.Name))
            .Where(v => !string.IsNullOrWhiteSpace(v))
            .ToList();

        switch (field.Type)
        {
            case FieldType.Number:
                if (values.All(v => decimal.TryParse(v, NumberStyles.Float, CultureInfo.InvariantCulture, out _)))
                    return "DECIMAL(19,4)";
                break;

            case FieldType.Date:
                if (values.All(v => DateOnly.TryParse(v, CultureInfo.InvariantCulture,
                        DateTimeStyles.None, out _)))
                    return "DATE";
                break;
        }

        var maxLen = values.Count == 0 ? 0 : values.Max(v => v.Length);
        var size = maxLen switch
        {
            <= 48 => 64,
            <= 112 => 128,
            <= 240 => 256,
            <= 496 => 512,
            <= 1008 => 1024,
            <= 2032 => 2048,
            <= 4080 => 4096,
            _ => 32672,
        };
        return $"VARCHAR({size})";
    }

    private static string SqlLiteral(FieldDef field, string value)
    {
        if (string.IsNullOrEmpty(value))
            return field.Type == FieldType.Text ? "''" : "NULL";

        switch (field.Type)
        {
            case FieldType.Number when decimal.TryParse(value, NumberStyles.Float,
                CultureInfo.InvariantCulture, out var number):
                return number.ToString(CultureInfo.InvariantCulture);

            case FieldType.Date when DateOnly.TryParse(value, CultureInfo.InvariantCulture,
                DateTimeStyles.None, out _):
                return $"'{value.Trim()}'";

            default:
                return $"'{value.Replace("'", "''")}'";
        }
    }

    private static string Quote(string identifier)
        => "\"" + identifier.Replace("\"", "\"\"") + "\"";

    // ---------------------------------------------------------------- ODF front-end

    private static string BuildContentXml(TableDocument table)
    {
        var sb = new StringBuilder();
        sb.Append("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n");
        sb.Append("<office:document-content\n");
        sb.Append(" xmlns:office=\"urn:oasis:names:tc:opendocument:xmlns:office:1.0\"\n");
        sb.Append(" xmlns:db=\"urn:oasis:names:tc:opendocument:xmlns:database:1.0\"\n");
        sb.Append(" xmlns:xlink=\"http://www.w3.org/1999/xlink\"\n");
        sb.Append(" office:version=\"1.3\">\n");
        sb.Append("<office:body><office:database>\n");

        sb.Append("<db:data-source>\n");
        sb.Append("<db:connection-data>");
        sb.Append("<db:connection-resource xlink:href=\"sdbc:embedded:hsqldb\"/>");
        sb.Append("<db:login db:is-password-required=\"false\"/>");
        sb.Append("</db:connection-data>\n");
        sb.Append("<db:driver-settings db:system-driver-settings=\"\" db:base-dn=\"\" db:parameter-name-substitution=\"false\"/>\n");
        sb.Append("<db:application-connection-settings db:is-table-name-length-limited=\"false\" db:append-table-alias-name=\"false\" db:max-row-count=\"1000\">");
        sb.Append("<db:table-filter><db:table-include-filter><db:table-filter-pattern>%</db:table-filter-pattern></db:table-include-filter></db:table-filter>");
        sb.Append("</db:application-connection-settings>\n");
        sb.Append("</db:data-source>\n");

        var name = string.IsNullOrWhiteSpace(table.Name) ? "Table1" : table.Name;
        sb.Append("<db:table-representations>");
        sb.Append("<db:table-representation db:name=\"").Append(Escape(name)).Append("\"/>");
        sb.Append("</db:table-representations>\n");

        sb.Append("</office:database></office:body>\n");
        sb.Append("</office:document-content>");
        return sb.ToString();
    }

    private static string BuildManifest()
    {
        var sb = new StringBuilder();
        sb.Append("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n");
        sb.Append("<manifest:manifest\n");
        sb.Append(" xmlns:manifest=\"urn:oasis:names:tc:opendocument:xmlns:manifest:1.0\"\n");
        sb.Append(" manifest:version=\"1.3\">\n");
        sb.Append("<manifest:file-entry manifest:full-path=\"/\" manifest:version=\"1.3\" manifest:media-type=\"")
          .Append(BaseMime).Append("\"/>\n");
        foreach (var part in new[] { "content.xml", "settings.xml" })
            sb.Append("<manifest:file-entry manifest:full-path=\"").Append(part)
              .Append("\" manifest:media-type=\"text/xml\"/>\n");
        foreach (var part in new[] { "database/script", "database/properties" })
            sb.Append("<manifest:file-entry manifest:full-path=\"").Append(part)
              .Append("\" manifest:media-type=\"text/plain\"/>\n");
        sb.Append("</manifest:manifest>");
        return sb.ToString();
    }

    private static string SettingsXml() =>
        "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n" +
        "<office:document-settings\n" +
        " xmlns:office=\"urn:oasis:names:tc:opendocument:xmlns:office:1.0\"\n" +
        " office:version=\"1.3\">\n" +
        "<office:settings/>\n" +
        "</office:document-settings>";

    private static string Escape(string s)
        => s.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;")
            .Replace("\"", "&quot;").Replace("'", "&apos;");

    private static void AddEntry(ZipArchive zip, string name, string text)
    {
        var entry = zip.CreateEntry(name, CompressionLevel.Optimal);
        using var s = entry.Open();
        var bytes = Encoding.UTF8.GetBytes(text);
        s.Write(bytes, 0, bytes.Length);
    }
}
