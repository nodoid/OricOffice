using System.Text;
using Microsoft.Data.Sqlite;
using OricOffice.Core.Model;

namespace OricOffice.Core.Export;

/// <summary>
/// Base exports: a ready-to-run SQL script for MySQL and Microsoft SQL Server,
/// and a real SQLite database file. All three create the records table and
/// insert every record in the document.
/// </summary>
public static class SqlExporters
{
    private const int BatchSize = 100;

    // ---------------------------------------------------------------- MySQL

    public static string ExportMysqlScript(OricFile file)
    {
        var table = file.Table;
        var name = EscapeMysqlId(table.Name);
        var sb = new StringBuilder();
        sb.Append("-- Generated by Oric Office (Oric Base)\n");
        sb.Append("-- Source: ").Append(SafeComment(file.Title)).Append('\n');
        sb.Append("-- Dialect: MySQL 8.x   |   Licensed under DILLIGAF © Paul F. Johnson\n");
        sb.Append("SET NAMES utf8mb4;\n\n");
        sb.Append("CREATE TABLE IF NOT EXISTS ").Append(name).Append(" (\n");
        sb.Append("    `id` INT NOT NULL AUTO_INCREMENT,\n");
        for (int i = 0; i < table.Fields.Count; i++)
        {
            var field = table.Fields[i];
            sb.Append("    ").Append(EscapeMysqlId(field.Name)).Append(' ')
              .Append(MysqlType(field.Type)).Append(" NULL");
            sb.Append(i == table.Fields.Count - 1 ? "\n" : ",\n");
        }
        sb.Append(table.Fields.Count == 0
            ? "    PRIMARY KEY (`id`)\n"
            : ",\n    PRIMARY KEY (`id`)\n");
        sb.Append(") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;\n\n");

        var columns = string.Join(", ", table.Fields.Select(f => EscapeMysqlId(f.Name)));
        for (int start = 0; start < table.Records.Count; start += BatchSize)
        {
            var batch = table.Records.Skip(start).Take(BatchSize);
            sb.Append("INSERT INTO ").Append(name)
              .Append(" (").Append(columns).Append(") VALUES\n");
            bool first = true;
            foreach (var record in batch)
            {
                if (!first) sb.Append(",\n");
                first = false;
                sb.Append("  (").Append(string.Join(", ",
                    table.Fields.Select(f => MysqlLiteral(record, f)))).Append(')');
            }
            sb.Append(";\n\n");
        }

        return sb.ToString();
    }

    private static string MysqlType(FieldType type) => type switch
    {
        FieldType.Number => "DOUBLE",
        FieldType.Date => "DATE",
        _ => "VARCHAR(255)",
    };

    private static string MysqlLiteral(RecordRow record, FieldDef field)
    {
        if (!record.Values.TryGetValue(field.Name, out var value) || value is null)
            return "NULL";
        return field.Type switch
        {
            FieldType.Number => double.TryParse(value,
                System.Globalization.NumberStyles.Any,
                System.Globalization.CultureInfo.InvariantCulture, out var d)
                ? d.ToString(System.Globalization.CultureInfo.InvariantCulture)
                : "NULL",
            FieldType.Date => DateTime.TryParse(value,
                System.Globalization.CultureInfo.InvariantCulture,
                System.Globalization.DateTimeStyles.None, out var dt)
                ? "'" + dt.ToString("yyyy-MM-dd") + "'"
                : "NULL",
            _ => value.Length == 0
                ? "''"
                : "'" + value.Replace("\\", "\\\\")
                    .Replace("'", "\\'")
                    .Replace("\0", "\\0")
                    .Replace("\n", "\\n")
                    .Replace("\r", "\\r")
                    .Replace("\x1A", "\\Z") + "'",
        };
    }

    private static string EscapeMysqlId(string id)
    {
        var clean = new string(id.Where(c => !char.IsControl(c)).ToArray());
        return "`" + clean.Replace("`", "``") + "`";
    }

    // ---------------------------------------------------------------- MSSQL

    public static string ExportMssqlScript(OricFile file)
    {
        var table = file.Table;
        var name = EscapeMssqlId(table.Name);
        var sb = new StringBuilder();
        sb.Append("-- Generated by Oric Office (Oric Base)\n");
        sb.Append("-- Source: ").Append(SafeComment(file.Title)).Append('\n');
        sb.Append("-- Dialect: Microsoft SQL Server   |   Licensed under DILLIGAF © Paul F. Johnson\n\n");
        sb.Append("CREATE TABLE ").Append(name).Append(" (\n");
        sb.Append("    [id] INT IDENTITY(1,1) PRIMARY KEY,\n");
        for (int i = 0; i < table.Fields.Count; i++)
        {
            var field = table.Fields[i];
            sb.Append("    ").Append(EscapeMssqlId(field.Name)).Append(' ')
              .Append(MssqlType(field.Type)).Append(" NULL");
            sb.Append(i == table.Fields.Count - 1 ? "\n" : ",\n");
        }
        sb.Append(");\nGO\n\n");

        var columns = string.Join(", ", table.Fields.Select(f => EscapeMssqlId(f.Name)));
        for (int start = 0; start < table.Records.Count; start += BatchSize)
        {
            var batch = table.Records.Skip(start).Take(BatchSize);
            sb.Append("INSERT INTO ").Append(name)
              .Append(" (").Append(columns).Append(") VALUES\n");
            bool first = true;
            foreach (var record in batch)
            {
                if (!first) sb.Append(",\n");
                first = false;
                sb.Append("  (").Append(string.Join(", ",
                    table.Fields.Select(f => MssqlLiteral(record, f)))).Append(')');
            }
            sb.Append(";\nGO\n\n");
        }

        return sb.ToString();
    }

    private static string MssqlType(FieldType type) => type switch
    {
        FieldType.Number => "FLOAT",
        FieldType.Date => "DATE",
        _ => "NVARCHAR(255)",
    };

    private static string MssqlLiteral(RecordRow record, FieldDef field)
    {
        if (!record.Values.TryGetValue(field.Name, out var value) || value is null)
            return "NULL";
        return field.Type switch
        {
            FieldType.Number => double.TryParse(value,
                System.Globalization.NumberStyles.Any,
                System.Globalization.CultureInfo.InvariantCulture, out var d)
                ? d.ToString(System.Globalization.CultureInfo.InvariantCulture)
                : "NULL",
            FieldType.Date => DateTime.TryParse(value,
                System.Globalization.CultureInfo.InvariantCulture,
                System.Globalization.DateTimeStyles.None, out var dt)
                ? "'" + dt.ToString("yyyy-MM-dd") + "'"
                : "NULL",
            _ => value.Length == 0
                ? "''"
                : "N'" + value.Replace("'", "''") + "'",
        };
    }

    private static string EscapeMssqlId(string id)
    {
        var clean = new string(id.Where(c => !char.IsControl(c)).ToArray());
        return "[" + clean.Replace("]", "]]") + "]";
    }

    // ---------------------------------------------------------------- SQLite

    /// <summary>Writes a real SQLite database file containing the records table.</summary>
    public static void ExportSqlite(OricFile file, string path)
    {
        var dir = Path.GetDirectoryName(Path.GetFullPath(path));
        if (!string.IsNullOrEmpty(dir)) Directory.CreateDirectory(dir);
        if (File.Exists(path)) File.Delete(path);

        var table = file.Table;
        var tableName = CleanSqliteId(table.Name);

        var connectionString = new SqliteConnectionStringBuilder
        {
            DataSource = path,
            Mode = SqliteOpenMode.ReadWriteCreate,
            Pooling = false,
        }.ToString();

        using var connection = new SqliteConnection(connectionString);
        connection.Open();

        using (var create = connection.CreateCommand())
        {
            var sb = new StringBuilder();
            sb.Append("CREATE TABLE ").Append(QuoteSqliteId(tableName)).Append(" (\n");
            sb.Append("    \"id\" INTEGER PRIMARY KEY AUTOINCREMENT");
            foreach (var field in table.Fields)
            {
                sb.Append(",\n    ").Append(QuoteSqliteId(CleanSqliteId(field.Name)))
                  .Append(' ').Append(SqliteType(field.Type)).Append(" NULL");
            }
            sb.Append("\n)");
            create.CommandText = sb.ToString();
            create.ExecuteNonQuery();
        }

        using var transaction = connection.BeginTransaction();
        foreach (var record in table.Records)
        {
            using var insert = connection.CreateCommand();
            var columnNames = string.Join(", ", table.Fields
                .Select(f => QuoteSqliteId(CleanSqliteId(f.Name))));
            insert.CommandText = "INSERT INTO " + QuoteSqliteId(tableName) +
                " (" + columnNames + ") VALUES (" +
                string.Join(", ", table.Fields.Select((_, i) => "$v" + i)) + ")";
            for (int i = 0; i < table.Fields.Count; i++)
            {
                var field = table.Fields[i];
                if (!record.Values.TryGetValue(field.Name, out var value) || value is null)
                {
                    insert.Parameters.AddWithValue("$v" + i, DBNull.Value);
                    continue;
                }
                object parameterValue = field.Type switch
                {
                    FieldType.Number when double.TryParse(value,
                        System.Globalization.NumberStyles.Any,
                        System.Globalization.CultureInfo.InvariantCulture, out var d) => d,
                    FieldType.Number => DBNull.Value,
                    FieldType.Date when DateTime.TryParse(value,
                        System.Globalization.CultureInfo.InvariantCulture,
                        System.Globalization.DateTimeStyles.None, out var dt)
                        => dt.ToString("yyyy-MM-dd"),
                    _ => value,
                };
                insert.Parameters.AddWithValue("$v" + i, parameterValue);
            }
            insert.ExecuteNonQuery();
        }
        transaction.Commit();
    }

    private static string SqliteType(FieldType type) => type switch
    {
        FieldType.Number => "REAL",
        FieldType.Date => "TEXT",
        _ => "TEXT",
    };

    private static string CleanSqliteId(string id)
    {
        var clean = new string(id.Where(c => !char.IsControl(c)).ToArray());
        return clean.Length == 0 ? "field" : clean;
    }

    private static string QuoteSqliteId(string id) => "\"" + id.Replace("\"", "\"\"") + "\"";

    private static string SafeComment(string? text)
    {
        if (string.IsNullOrWhiteSpace(text)) return "Untitled";
        return new string(text.Select(c => c is '\n' or '\r' ? ' ' : c).ToArray());
    }
}
